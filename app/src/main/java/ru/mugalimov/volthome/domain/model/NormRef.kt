package ru.mugalimov.volthome.domain.model

/**
 * Ссылка на нормативный источник (ПУЭ / СП / ГОСТ и т.п.).
 * Это НЕ текст норматива, а идентификатор и метаданные для отображения/ссылки.
 */
data class NormRef(
    /** Короткий код источника: "ПУЭ", "СП", "ГОСТ" */
    val source: String,
    /** Идентификатор раздела/пункта: "1.3.10", "256.1325800.2016 п.7.2" */
    val section: String,
    /** Заголовок/короткое описание пункта (по желанию) */
    val title: String? = null
)