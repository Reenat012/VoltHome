package ru.mugalimov.volthome.ui.manual

/**
 * Запрещённые действия во время ручного режима.
 * Используются ТОЛЬКО для корректного текста в едином guard-диалоге.
 *
 * Важно:
 * - enum НЕ содержит логики
 * - enum НЕ решает, можно ли действие
 * - он лишь описывает, КАК объяснить пользователю, что происходит
 */
enum class ForbiddenAction(
    val title: String,
    val message: String
) {

    SWITCH_PROJECT(
        title = "Смена проекта недоступна",
        message = "Сейчас включён ручной режим. Перед сменой проекта нужно сохранить изменения или отменить их."
    ),

    EXPORT_PDF(
        title = "PDF недоступен в ручном режиме",
        message = "Сейчас включён ручной режим. Перед созданием PDF нужно сохранить изменения или отменить их, иначе отчёт будет невалидным."
    ),

    AUTO_RECALC(
        title = "Пересчёт недоступен в ручном режиме",
        message = "Сейчас включён ручной режим. Автоматический пересчёт затрёт ручные изменения. Сначала сохраните их или отмените."
    ),

    REINIT_PROJECT(
        title = "Переинициализация недоступна",
        message = "Сейчас включён ручной режим. Переинициализация проекта затрёт все ручные изменения. Сначала сохраните их или отмените."
    ),

    /**
     * Выход из ручного режима — это тоже «опасное действие»,
     * потому что пользователь может потерять внесённые изменения.
     *
     * Используется при повторном клике на «Ручной режим».
     */
    LEAVE_MANUAL_MODE(
        title = "Выйти из ручного режима?",
        message = "Вы внесли ручные изменения. Их можно сохранить или отменить и вернуться к автоматическому расчёту."
    )
}